"""Shared plumbing for the experiment scripts.

Every experiment is the same shape: change one variable, re-run the gold set,
write a markdown table into docs/experiments/. Keeping that shape in one place
is what makes each experiment a 40-line file instead of a forked pipeline.
"""

from __future__ import annotations

import time
from collections.abc import Sequence
from pathlib import Path

from src.chunking import code_chunker
from src.config import ROOT, Config
from src.embeddings.embedder import Embedder
from src.eval import runner
from src.eval.gold import load_gold
from src.eval.metrics import Summary
from src.parser import repo_fetcher, repository_loader
from src.retrieval.reranker import CrossEncoderReranker
from src.vector_store import qdrant_store

DOCS = ROOT / "docs" / "experiments"


def base_cfg(repo: str | None = None, gold: str | None = None, **overrides) -> Config:
    """A Config for one experiment run, optionally pointed at the second corpus."""
    cfg = Config(**overrides)
    if repo:
        cfg = cfg.override(repo=repo)
    if gold:
        cfg = cfg.override(gold_set=ROOT / "eval" / f"{gold}.json")
    return cfg


def corpus_label(cfg: Config) -> str:
    return f"{qdrant_store.repo_slug(cfg.repo)}"


def checkout_path(cfg: Config) -> Path:
    owner, name = repo_fetcher.parse_repo_url(cfg.repo)
    existing = sorted(cfg.repos_dir.glob(f"{owner}__{name}@*"))
    if existing:
        return existing[0]
    return repo_fetcher.fetch(cfg).path


def load_files(cfg: Config):
    return repository_loader.load(checkout_path(cfg), cfg)


def ensure_index(cfg: Config, files) -> tuple[qdrant_store.QdrantStore, Embedder, int]:
    """Index this (repo, model, strategy) combination if it is not already there."""
    store = qdrant_store.QdrantStore(cfg)
    embedder = Embedder(cfg)
    chunks = code_chunker.chunk(files, cfg, cfg.strategy)
    report = store.sync(chunks, embedder.embed_batch)
    return store, embedder, report.points


def harness_for(cfg: Config, files, with_reranker: bool = False) -> runner.Harness:
    store, embedder, _ = ensure_index(cfg, files)
    harness = runner.Harness.build(cfg, files)
    harness.store, harness.embedder = store, embedder
    if with_reranker:
        harness.reranker = CrossEncoderReranker(cfg)
    return harness


def gold_for(cfg: Config) -> dict:
    return load_gold(cfg.gold_set)


def evaluate(harness: runner.Harness, retrievers: Sequence[str], top_k: int = 5) -> list[Summary]:
    return runner.evaluate(harness, gold_for(harness.cfg), retrievers, top_k=top_k, dump_dir=None)


def md_table(headers: Sequence[str], rows: Sequence[Sequence[object]]) -> str:
    head = "| " + " | ".join(headers) + " |"
    rule = "| " + " | ".join("---" for _ in headers) + " |"
    body = ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join([head, rule, *body])


def summary_row(label: str, summary: Summary) -> list[object]:
    return [
        label,
        f"{summary.hit_at_1:.2f}",
        f"{summary.hit_at_5:.2f}",
        f"{summary.recall_at_5:.2f}",
        f"{summary.mrr:.2f}",
        f"{summary.ndcg_at_5:.2f}",
        f"{summary.mean_ms:.1f}",
    ]


SUMMARY_HEADERS = ("variant", "hit@1", "hit@5", "rec@5", "mrr", "ndcg@5", "ms")


def write(name: str, title: str, body: str, cfg: Config | None = None) -> Path:
    """One markdown file per experiment, stamped so a stale table is obvious."""
    DOCS.mkdir(parents=True, exist_ok=True)
    suffix = f"-{corpus_label(cfg).split('__')[-1].lower()}" if cfg else ""
    path = DOCS / name.replace(".md", f"{suffix}.md")
    corpus = f"Corpus: `{cfg.repo}` ({cfg.strategy} chunking).\n\n" if cfg else ""
    stamp = time.strftime("%Y-%m-%d")
    path.write_text(
        f"# {title}\n\n_Generated by `{Path(__file__).parent.name}/` on {stamp}._\n\n{corpus}{body}\n"
    )
    print(f"wrote {path.relative_to(ROOT)}")
    return path
